class GeometrySnapshot {
  final double? lowerBreakeven;
  final double? upperBreakeven;
  final double? wingWidth;
  final double? distanceToLowerBreakeven;
  final double? distanceToUpperBreakeven;
  final double? profitRange;

  const GeometrySnapshot({
    required this.lowerBreakeven,
    required this.upperBreakeven,
    required this.wingWidth,
    required this.distanceToLowerBreakeven,
    required this.distanceToUpperBreakeven,
    required this.profitRange,
  });
}
